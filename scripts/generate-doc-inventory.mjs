// generate-doc-inventory.mjs — documentation-only generator (Node fs/path only,
// no new dependencies). Produces docs/generated/{repository-tree,source-inventory,
// dependency-inventory}.md. Run: node scripts/generate-doc-inventory.mjs
import fs from 'fs';
import path from 'path';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'docs', 'generated');
fs.mkdirSync(OUT, { recursive: true });

const SKIP_DIRS = new Set(['node_modules', 'dist', '.git', 'generated']);

function walk(dir, base = '') {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => !SKIP_DIRS.has(e.name))
    .sort((a, b) => Number(b.isDirectory()) - Number(a.isDirectory()) || a.name.localeCompare(b.name));
  const files = [];
  for (const e of entries) {
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) files.push(...walk(path.join(dir, e.name), rel));
    else files.push(rel);
  }
  return files;
}

const allFiles = walk(ROOT);
const stamp = 'Generated by scripts/generate-doc-inventory.mjs — do not edit by hand; rerun after structural changes.';

// 1. repository-tree.md
const treeLines = allFiles.map((f) => `- \`${f}\``);
fs.writeFileSync(path.join(OUT, 'repository-tree.md'),
  `# Repository Tree\n\n> ${stamp}\n\n${treeLines.length} tracked files (excludes node_modules/, dist/, .git/, docs/generated/).\n\n${treeLines.join('\n')}\n`);

// 2. source-inventory.md (src/, public/, scripts/, tests/ with line counts)
const codeExt = new Set(['.ts', '.tsx', '.js', '.css', '.html', '.json']);
const inv = allFiles
  .filter((f) => /^(src|public|scripts|tests)\//.test(f) && codeExt.has(path.extname(f)))
  .map((f) => {
    const lines = fs.readFileSync(path.join(ROOT, f), 'utf8').split('\n').length;
    return { f, lines };
  }).sort((a, b) => b.lines - a.lines);
const total = inv.reduce((n, r) => n + r.lines, 0);
fs.writeFileSync(path.join(OUT, 'source-inventory.md'),
  `# Source Inventory\n\n> ${stamp}\n\nTotal: ${inv.length} files, ${total} lines.\n\n| Lines | File |\n|---:|---|\n${inv.map((r) => `| ${r.lines} | \`${r.f}\` |`).join('\n')}\n`);

// 3. dependency-inventory.md (package.json deps + import scan of src/)
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const deps = { ...pkg.dependencies, ...pkg.devDependencies };
const importRe = /(?:from|require\()\s*['"]([^.'"][^'"]*)['"]/g;
const used = new Map();
for (const f of allFiles.filter((f) => /^src\//.test(f) && /\.tsx?$/.test(f))) {
  const text = fs.readFileSync(path.join(ROOT, f), 'utf8');
  for (const m of text.matchAll(importRe)) {
    const spec = m[1];
    const name = spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0];
    if (!used.has(name)) used.set(name, new Set());
    used.get(name).add(f);
  }
}
const rows = Object.keys(deps).map((name) => {
  const consumers = used.get(name);
  return `| \`${name}\` | ${deps[name]} | ${consumers ? [...consumers].length + ' src file(s): ' + [...consumers].map((c) => `\`${c}\``).join(', ') : 'none found in src/ imports (build tooling or template leftover)' } |`;
});
fs.writeFileSync(path.join(OUT, 'dependency-inventory.md'),
  `# Dependency Inventory\n\n> ${stamp}\n\n| Package | Version | Used by |\n|---|---|---|\n${rows.join('\n')}\n`);
console.log(`OK: ${allFiles.length} files, ${inv.length} source files (${total} lines), ${Object.keys(deps).length} package.json dependencies.`);
